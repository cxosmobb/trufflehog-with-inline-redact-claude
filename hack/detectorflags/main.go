// Command detectorflags writes pkg/redact/detector_flags_test.go, the list of
// feature flags that gate detectors, which the redaction tests turn on the way
// the CLI does. Upstream adds such flags with most new detectors and removes
// them once a detector graduates, so the upstream sync reruns this after every
// merge. Run it from the repository root: go run ./hack/detectorflags
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const header = `// Code generated by go run ./hack/detectorflags; DO NOT EDIT.

package redact

import (
	"sync/atomic"

	"github.com/trufflesecurity/trufflehog/v3/pkg/feature"
)

// detectorFeatureFlags are the feature flags that gate detectors. The CLI
// (main.go) turns all of them on, so the tests do too.
var detectorFeatureFlags = map[string]*atomic.Bool{
`

func main() {
	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join("pkg", "feature", "feature.go"), nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var flags []string
	ast.Inspect(file, func(n ast.Node) bool {
		if spec, ok := n.(*ast.ValueSpec); ok {
			for _, name := range spec.Names {
				if strings.HasSuffix(name.Name, "DetectorEnabled") {
					flags = append(flags, name.Name)
				}
			}
		}
		return true
	})
	slices.Sort(flags)

	var b bytes.Buffer
	b.WriteString(header)
	for _, flag := range flags {
		fmt.Fprintf(&b, "\t%q: &feature.%s,\n", flag, flag)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join("pkg", "redact", "detector_flags_test.go"), src, 0o644); err != nil {
		log.Fatal(err)
	}
}
